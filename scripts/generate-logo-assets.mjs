import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";
import { colors } from "../lib/site.ts";

const logoFile = "public/lubajalogov1.svg";

const svg = readFileSync(logoFile, "utf8");
const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
const paths = Array.from(svg.matchAll(/<path[^>]*\sd="([^"]+)"/g), (m) => m[1]);
if (!viewBox || paths.length === 0) {
  throw new Error(`Couldn't find a viewBox and paths in ${logoFile}`);
}
const [, , width, height] = viewBox.split(/[\s,]+/).map(Number);

function tile({ size, padding, radius }) {
  const inner = size * (1 - 2 * padding);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <rect width="${size}" height="${size}" rx="${size * radius}" fill="${colors.brown}"/>
  <svg x="${size * padding}" y="${size * padding}" width="${inner}" height="${inner}" viewBox="${viewBox}" fill="#fff" fill-rule="evenodd">
    ${paths.map((d) => `<path d="${d}"/>`).join("\n    ")}
  </svg>
</svg>
`;
}

const rounded = (size) => tile({ size, padding: 0.1, radius: 0.2 });
// iOS and Android crop these to their own shapes, so the logo has to fit
// inside the maskable safe zone (a centered circle 80% of the icon wide).
const fullBleed = (size) => tile({ size, padding: 0.2, radius: 0 });

const png = (svg) => sharp(Buffer.from(svg)).png().toBuffer();

function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, i) => {
    const entry = 6 + 16 * i;
    header.writeUInt8(size % 256, entry);
    header.writeUInt8(size % 256, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((image) => image.data)]);
}

const logoModule = `// Generated by \`npm run logo\` from ${logoFile}. Don't edit by hand.
export const logo = {
  viewBox: "${viewBox}",
  width: ${width},
  height: ${height},
  paths: [
${paths.map((d) => `    "${d}",`).join("\n")}
  ],
} as const;
`;

const faviconImages = await Promise.all(
  [16, 32, 48].map(async (size) => ({ size, data: await png(rounded(size)) })),
);

const outputs = {
  "lib/logo-paths.ts": logoModule,
  "app/icon.svg": rounded(256),
  "app/favicon.ico": ico(faviconImages),
  "app/apple-icon.png": await png(fullBleed(180)),
  "public/icon-192.png": await png(rounded(192)),
  "public/icon-512.png": await png(rounded(512)),
  "public/icon-maskable-512.png": await png(fullBleed(512)),
};

for (const [file, data] of Object.entries(outputs)) {
  writeFileSync(file, data);
  console.log(`wrote ${file}`);
}
console.log(`from ${logoFile}`);
